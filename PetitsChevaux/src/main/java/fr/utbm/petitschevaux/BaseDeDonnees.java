package fr.utbm.petitschevaux;

import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Accès à la base de données H2 qui conserve les profils des joueurs et l'historique
 * des parties terminées. Les parties en cours, elles, sont sauvegardées dans des fichiers
 * (voir {@link Sauvegarde}).
 *
 * <p>Chaque opération ouvre une connexion courte : la base n'est verrouillée que le temps
 * de l'opération, ce qui permet de lancer deux fois le jeu sur le même ordinateur.</p>
 */
public final class BaseDeDonnees {
    /** Fichier de la base, dans le dossier depuis lequel le jeu est lancé (H2 ajoute « .mv.db »). */
    public static final Path FICHIER = Path.of(System.getProperty("user.dir"), "donnees", "petits-chevaux");

    private static final String[] TABLES = {
            """
            CREATE TABLE IF NOT EXISTS profil (
                nom VARCHAR(100) PRIMARY KEY,
                parties INT NOT NULL,
                victoires INT NOT NULL
            )""",
            """
            CREATE TABLE IF NOT EXISTS partie (
                id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                date_fin TIMESTAMP NOT NULL,
                mode VARCHAR(30) NOT NULL,
                vainqueur VARCHAR(100) NOT NULL,
                vainqueur_bot BOOLEAN NOT NULL,
                duree_ms BIGINT NOT NULL,
                lancers INT NOT NULL
            )"""
    };

    private final String url;
    private volatile boolean tablesCreees;

    /**
     * @param url adresse JDBC de la base (par exemple une base en mémoire dans les tests)
     */
    public BaseDeDonnees(String url) {
        this.url = url;
    }

    /**
     * @return la base du jeu, stockée dans {@link #FICHIER}
     */
    public static BaseDeDonnees parDefaut() {
        return new BaseDeDonnees("jdbc:h2:file:" + FICHIER.toAbsolutePath().toString().replace('\\', '/'));
    }

    /**
     * Ouvre une connexion ; les tables sont créées à la première ouverture.
     * La connexion doit être fermée par l'appelant (try-with-resources).
     */
    public Connection ouvrir() throws SQLException {
        Connection connexion = DriverManager.getConnection(url, "sa", "");
        if (!tablesCreees) {
            try (Statement requete = connexion.createStatement()) {
                for (String table : TABLES) {
                    requete.execute(table);
                }
            } catch (SQLException e) {
                connexion.close();
                throw e;
            }
            tablesCreees = true;
        }
        return connexion;
    }
}
